export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  // Match youtube.com/watch?v=XYZ
  const watchMatch = url.match(/[?&]v=([a-zA-Z0-9_-]{11})/);
  if (watchMatch && watchMatch[1]) return watchMatch[1];
  
  // Match youtube.com/live/XYZ
  const liveMatch = url.match(/youtube\.com\/live\/([a-zA-Z0-9_-]{11})/);
  if (liveMatch && liveMatch[1]) return liveMatch[1];

  // Match youtu.be/XYZ
  const shortMatch = url.match(/youtu\.be\/([a-zA-Z0-9_-]{11})/);
  if (shortMatch && shortMatch[1]) return shortMatch[1];

  // Match youtube.com/embed/XYZ or youtube-nocookie.com/embed/XYZ
  const embedMatch = url.match(/youtube(?:-nocookie)?\.com\/embed\/([a-zA-Z0-9_-]{11})/);
  if (embedMatch && embedMatch[1]) return embedMatch[1];

  // Match youtube.com/shorts/XYZ
  const shortsMatch = url.match(/youtube\.com\/shorts\/([a-zA-Z0-9_-]{11})/);
  if (shortsMatch && shortsMatch[1]) return shortsMatch[1];

  return null;
}

/**
 * Security: Validates that a string is a safe, valid web URL (strictly HTTP or HTTPS)
 * Blocks javascript:, data:, vbscript:, file:, blob: and ill-formed attack payloads
 */
export function isSafeWebUrl(url: string): boolean {
  if (!url || typeof url !== 'string') return false;
  const trimmed = url.trim();
  if (!trimmed.startsWith('https://') && !trimmed.startsWith('http://')) return false;
  if (/^(javascript|data|vbscript|file|blob|about):/i.test(trimmed)) return false;
  try {
    const parsed = new URL(trimmed);
    return parsed.protocol === 'https:' || parsed.protocol === 'http:';
  } catch {
    return false;
  }
}

/**
 * Security: Sanitizes user-provided channel titles and names against XSS and control code injection
 */
export function sanitizeText(input: string): string {
  if (!input || typeof input !== 'string') return '';
  return input
    .replace(/<[^>]*>/g, '') // Strip HTML tags
    .replace(/[\x00-\x1F\x7F]/g, '') // Strip ASCII control characters
    .trim();
}

export function parseNotepadToChannels(rawText: string): Channel[] {
  const lines = rawText.split('\n');
  const channels: Channel[] = [];
  let channelNumber = 1;
  const seenUrls = new Set<string>();

  // Check if it's M3U playlist format
  if (rawText.includes('#EXTM3U')) {
    return parseM3UPlaylist(rawText);
  }

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i].trim();
    if (!rawLine || rawLine.startsWith('#')) continue;

    // Line format can be:
    // tv:9,https://...
    // ntv:https://...
    // bakthi tv;https://...
    // Channel Name | https://...
    let namePart = '';
    let urlPart = '';

    const colonHttpIdx = rawLine.indexOf('http');
    if (colonHttpIdx > 0) {
      urlPart = rawLine.substring(colonHttpIdx).trim();
      namePart = rawLine.substring(0, colonHttpIdx);
      // Strip trailing punctuation like : or , or ;
      namePart = namePart.replace(/[:;,|]+$/, '').trim();
    } else {
      continue;
    }

    // Security hardening: validate URL protocol and format
    if (!urlPart || !isSafeWebUrl(urlPart) || seenUrls.has(urlPart)) {
      continue;
    }
    seenUrls.add(urlPart);

    // Sanitize title against script/HTML injection
    namePart = sanitizeText(namePart);

    const lookupKey = namePart.toLowerCase().replace(/[\s_-]+/g, ' ').trim();
    const meta = CHANNEL_METADATA[lookupKey] || findFuzzyMetadata(namePart) || findFuzzyMetadata(urlPart);

    const ytId = extractYouTubeId(urlPart) || (meta?.directYoutubeUrl ? extractYouTubeId(meta.directYoutubeUrl) : null);
    const isDirectHls = urlPart.includes('.m3u8');
    const mappedHls = meta?.directHlsUrl;

    let streamType: Channel['streamType'] = 'web';
    let streamUrl = urlPart;
    let embedUrl = urlPart;

    if (ytId) {
      streamType = 'youtube';
      embedUrl = `https://www.youtube.com/embed/${ytId}?autoplay=1&mute=0&rel=0&modestbranding=1&enablejsapi=1&playsinline=1`;
      streamUrl = urlPart.includes('youtube') || urlPart.includes('youtu.be') ? urlPart : (meta?.directYoutubeUrl || urlPart);
    } else if (isDirectHls) {
      streamType = 'hls';
      streamUrl = urlPart;
    } else if (mappedHls) {
      // Channel has direct official live stream feed (CDN)
      streamType = 'hls';
      streamUrl = mappedHls;
    } else {
      streamType = 'web';
      embedUrl = urlPart;
    }

    const cleanTitle = meta?.label || formatChannelTitle(namePart);
    const category = meta?.category || guessCategoryFromName(cleanTitle);
    const channelLogo = meta?.logo || generateLogoUrl(cleanTitle, meta?.logoColor || '#1e293b');

    channels.push({
      id: `ch-${channelNumber}-${ytId || Math.random().toString(36).substring(2, 7)}`,
      number: channelNumber,
      name: cleanTitle,
      originalUrl: urlPart,
      streamType,
      streamUrl,
      embedUrl,
      officialWebsite: meta?.officialWebsite,
      livePortalUrl: meta?.officialWebsite || (streamType === 'web' ? urlPart : undefined),
      category,
      logo: channelLogo,
      logoColor: meta?.logoColor || '#ea580c',
      quality: channelNumber % 3 === 0 ? '4K' : (channelNumber % 2 === 0 ? 'FHD' : 'HD'),
      isFavorite: ['tv9', 'ntv', 'bakthi', 'v6', 'tv5', 'sakshi', 'abn', 'aditya music', 'etv'].some(k => lookupKey.includes(k)),
      language: 'Telugu',
      epgCurrent: meta?.epg || `${cleanTitle} Live HD Broadcast`,
      epgNext: `${cleanTitle} Telugu Samacharam & Highlights`,
      description: `Official live TV broadcast for ${cleanTitle} in HD.`,
    });

    channelNumber++;
  }

  return channels;
}

export function findFuzzyMetadata(nameOrUrl: string) {
  if (!nameOrUrl) return null;
  const clean = nameOrUrl.toLowerCase().replace(/[^a-z0-9]/g, '');
  
  // 1. Check exact or substring key matching
  for (const [key, val] of Object.entries(CHANNEL_METADATA)) {
    const normKey = key.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (clean === normKey || clean.includes(normKey) || normKey.includes(clean)) {
      return val;
    }
  }

  // 2. Check matching by official website host or stream URL
  const lower = nameOrUrl.toLowerCase();
  for (const val of Object.values(CHANNEL_METADATA)) {
    if (val.officialWebsite && lower.includes(val.officialWebsite.toLowerCase().replace(/https?:\/\//, '').split('/')[0])) {
      return val;
    }
    if (val.directHlsUrl && lower.includes(val.directHlsUrl.toLowerCase())) {
      return val;
    }
  }

  return null;
}

/**
 * Returns a live Internet logo for a channel title, or fallback monogram SVG
 */
export function getChannelLogo(channelName: string, color?: string): string {
  const meta = findFuzzyMetadata(channelName);
  if (meta?.logo) return meta.logo;
  return generateLogoUrl(channelName, color || meta?.logoColor || '#ea580c');
}

/**
 * Refresh stored channels with real internet logos if they currently use older SVG monograms or missing logos
 */
export function refreshChannelLogos(channels: Channel[]): Channel[] {
  return channels.map(ch => {
    const meta = findFuzzyMetadata(ch.name) || findFuzzyMetadata(ch.originalUrl);
    if (meta?.logo) {
      return {
        ...ch,
        logo: meta.logo,
      };
    }
    // If channel logo is empty or generic, provide fallback
    if (!ch.logo) {
      return {
        ...ch,
        logo: generateLogoUrl(ch.name, '#ea580c'),
      };
    }
    return ch;
  });
}

function formatChannelTitle(raw: string): string {
  if (!raw) return 'Telugu Channel';
  let title = raw.replace(/[-_]/g, ' ').trim();
  // Capitalize words
  return title
    .split(' ')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

